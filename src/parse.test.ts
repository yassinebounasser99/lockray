describe("diffLockfiles", () => {
  const base = parseNpmLock(
    npmLock({
      "node_modules/lodash": { version: "4.17.20" },
      "node_modules/chalk": { version: "4.1.2" },
      "node_modules/left-pad": { version: "1.3.0" },
    }),
  );

  it("separates added, removed and upgraded packages", () => {
    const head = parseNpmLock(
      npmLock({
        "node_modules/lodash": { version: "4.17.21" },
        "node_modules/chalk": { version: "4.1.2" },
        "node_modules/zod": { version: "3.23.8" },
      }),
    );
    const d = diffLockfiles(base, head);
    expect(d.added.map((p) => p.name)).toEqual(["zod"]);
    expect(d.removed.map((p) => p.name)).toEqual(["left-pad"]);
    expect(d.upgraded).toEqual([{ name: "lodash", from: ["4.17.20"], to: ["4.17.21"] }]);
    expect(d.introduced.map((p) => `${p.name}@${p.version}`)).toEqual(["lodash@4.17.21", "zod@3.23.8"]);
    expect(d.modified).toEqual([]);
  });

  it("catches a changed source or hash on an unchanged version", () => {
    const head = parseNpmLock(
      npmLock({
        "node_modules/lodash": { version: "4.17.20", resolved: "https://evil.example.com/lodash-4.17.20.tgz" },
        "node_modules/chalk": { version: "4.1.2", integrity: "sha512-AAAA" },
        "node_modules/left-pad": { version: "1.3.0" },
      }),
    );
    expect(diffLockfiles(base, head).modified.map((m) => m.after.name)).toEqual(["chalk", "lodash"]);
  });

  it("treats the npm and yarn registry hosts as the same source", () => {
    const head = parseNpmLock(
      npmLock({
        "node_modules/lodash": { version: "4.17.20", resolved: "https://registry.yarnpkg.com/lodash/-/lodash-4.17.20.tgz" },
        "node_modules/chalk": { version: "4.1.2" },
        "node_modules/left-pad": { version: "1.3.0" },
      }),
    );
    expect(diffLockfiles(base, head).modified).toEqual([]);
  });
});
