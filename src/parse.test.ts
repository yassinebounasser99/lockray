import { describe, expect, it } from "vitest";
import { diffLockfiles } from "./diff.js";
import { parseLockfile } from "./parse/index.js";
import { parseNpmLock } from "./parse/npm.js";
import { parseYarnLock } from "./parse/yarn.js";
import { npmLock } from "./test-helpers.js";

describe("parseNpmLock", () => {
  it("reads v3 packages, including nested and scoped ones", () => {
    const lock = parseNpmLock(
      npmLock({
        "node_modules/lodash": { version: "4.17.21", license: "MIT" },
        "node_modules/@babel/core": { version: "7.24.0", dev: true },
        "node_modules/a/node_modules/lodash": { version: "3.10.1" },
        "node_modules/esbuild": { version: "0.25.0", hasInstallScript: true },
      }),
    );
    expect([...lock.packages.keys()].sort()).toEqual(["@babel/core@7.24.0", "esbuild@0.25.0", "lodash@3.10.1", "lodash@4.17.21"]);
    expect(lock.packages.get("esbuild@0.25.0")?.hasInstallScript).toBe(true);
    expect(lock.packages.get("lodash@4.17.21")?.license).toBe("MIT");
  });

  it("skips the root project and linked workspaces", () => {
    const text = JSON.stringify({
      lockfileVersion: 3,
      packages: {
        "": { name: "app", version: "1.0.0" },
        "packages/ui": { name: "ui", version: "0.0.1" },
        "node_modules/ui": { resolved: "packages/ui", link: true },
      },
    });
    expect(parseNpmLock(text).packages.size).toBe(0);
  });

  it("falls back to the v1 dependency tree", () => {
    const text = JSON.stringify({
      lockfileVersion: 1,
      dependencies: {
        express: { version: "4.18.2", resolved: "https://registry.npmjs.org/express/-/express-4.18.2.tgz", dependencies: { debug: { version: "2.6.9" } } },
      },
    });
    expect([...parseNpmLock(text).packages.keys()].sort()).toEqual(["debug@2.6.9", "express@4.18.2"]);
  });
});

